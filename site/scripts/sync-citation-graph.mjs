import { writeFile } from "node:fs/promises";
import { papers } from "../src/data/papers.js";
import { citationEdges as existingEdges } from "../src/data/citationGraph.js";

const API_ROOT = "https://api.semanticscholar.org/graph/v1";
const corpusIds = new Set(papers.map((paper) => paper.id));

// Preserve all bibliography checks from original PDFs when refreshing API data.
const pdfVerifiedEdges = existingEdges.filter((edge) =>
  edge.verifiedBy === "paper-pdf" && corpusIds.has(edge.source) && corpusIds.has(edge.target));

const wait = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

async function fetchWithRetry(url) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const response = await fetch(url);
    if (response.ok) return response;
    if (response.status !== 429 || attempt === 4) {
      throw new Error(`Semantic Scholar request failed (${response.status}): ${url}`);
    }
    await wait(1000 * (attempt + 1));
  }
  throw new Error(`Semantic Scholar request failed: ${url}`);
}

async function fetchReferences(arxivId) {
  const references = [];
  let offset = 0;
  do {
    const url = `${API_ROOT}/paper/ARXIV:${arxivId}/references?fields=title,externalIds&limit=1000&offset=${offset}`;
    const response = await fetchWithRetry(url);
    const payload = await response.json();
    references.push(...(payload.data ?? []));
    offset = payload.next ?? 0;
  } while (offset > 0);
  return references;
}

const semanticScholarEdges = [];
for (const paper of papers) {
  const references = await fetchReferences(paper.id);
  for (const reference of references) {
    const target = reference.citedPaper?.externalIds?.ArXiv;
    if (target && target !== paper.id && corpusIds.has(target)) {
      semanticScholarEdges.push({ source: paper.id, target, verifiedBy: "semantic-scholar" });
    }
  }
  await wait(150);
}

const edges = [...semanticScholarEdges, ...pdfVerifiedEdges]
  .filter((edge, index, all) => all.findIndex((candidate) =>
    candidate.source === edge.source && candidate.target === edge.target) === index)
  .sort((left, right) => left.source.localeCompare(right.source) || left.target.localeCompare(right.target));

const snapshot = new Date().toISOString().slice(0, 10);
const output = `// Generated by scripts/sync-citation-graph.mjs.\n// Each edge points from the citing paper to the paper in its bibliography.\nexport const citationGraphMeta = ${JSON.stringify({
  snapshot,
  scope: "Current awesome-rsi corpus only",
  sourceName: "Semantic Scholar Academic Graph API",
  sourceUrl: "https://www.semanticscholar.org/product/api",
  semanticScholarEdges: edges.filter((edge) => edge.verifiedBy === "semantic-scholar").length,
  pdfVerifiedEdges: edges.filter((edge) => edge.verifiedBy === "paper-pdf").length,
  pdfFallbackPapers: [...new Set(edges.filter((edge) => edge.verifiedBy === "paper-pdf").map((edge) => edge.source))].sort(),
}, null, 2)};\n\nexport const citationEdges = ${JSON.stringify(edges, null, 2)};\n`;

await writeFile(new URL("../src/data/citationGraph.js", import.meta.url), output, "utf8");
console.log(`Wrote ${edges.length} verified citation edges.`);
